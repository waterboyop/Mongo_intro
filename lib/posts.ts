/** 以全文字數估算閱讀時間（中文約每分鐘 400 字） */
export function readingMinutes(post: Post) {
  const chars = post.body.reduce(
    (n, b) => n + (Array.isArray(b.x) ? b.x.join("").length : b.x.length),
    0,
  );
  return Math.max(1, Math.round(chars / 400));
}

